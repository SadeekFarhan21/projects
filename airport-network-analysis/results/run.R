suppressMessages({library(tidyverse);library(igraph)})
df <- read.csv("sampled_flights.csv")
cat("flights rows:",nrow(df),"\n")
cat("date range:",min(df$day),max(df$day),"\n")
s <- df |> select(origin,destination,latitude_1,longitude_1,latitude_2,longitude_2) |> drop_na()
cat("rows after drop_na:",nrow(s),"\n")
edges <- s |> group_by(origin,destination) |> summarise(weight=n(),.groups="drop")
o <- s |> select(name=origin,lat=latitude_1,long=longitude_1); d <- s |> select(name=destination,lat=latitude_2,long=longitude_2)
nodes <- bind_rows(o,d) |> distinct(name,.keep_all=TRUE) |> na.omit()
g <- graph_from_data_frame(edges,vertices=nodes,directed=TRUE)
g <- simplify(g,remove.multiple=TRUE,remove.loops=TRUE)
u <- as.undirected(g,mode="collapse")
wc <- components(g,mode="weak")
print(data.frame(V=vcount(g),E=ecount(g),simple=is_simple(g),weak=is_connected(g,"weak"),strong=is_connected(g,"strong"),ncomp=wc$no,lcc=max(wc$csize),diam=diameter(g,weights=NA),apl=round(mean_distance(g),4),dens=round(edge_density(g),6)))
cat("undirected E:",ecount(u),"\n")
cat("vconn",vertex_connectivity(u),"econn",edge_connectivity(u),"ncomp",components(u)$no,"isolates",sum(degree(u)==0),"\n")
cat("trans global",round(transitivity(u,type="global"),4),"avg local",round(mean(transitivity(u,type="local"),na.rm=TRUE),4),"\n")
cat("max degree",max(degree(u)),"median deg",median(degree(u)),"mean deg",round(mean(degree(u)),3),"share deg<=2", round(mean(degree(u)<=2),3),"\n")
print(head(sort(degree(u),decreasing=TRUE),10))
comp <- components(u); lcc <- induced_subgraph(u,which(comp$membership==which.max(comp$csize)))
print(round(head(sort(closeness(lcc),decreasing=TRUE),10),6))
print(round(head(sort(betweenness(u,normalized=TRUE),decreasing=TRUE),10),6))
print(round(head(sort(eigen_centrality(u)$vector,decreasing=TRUE),10),6))
print(round(head(sort(hub_score(g)$vector,decreasing=TRUE),10),4))
print(round(head(sort(authority_score(g)$vector,decreasing=TRUE),10),4))
print(head(sort(strength(u),decreasing=TRUE),10))
cd <- data.frame(deg=degree(u),bet=betweenness(u),eig=eigen_centrality(u)$vector,str=strength(u))
print(round(cor(cd,method="spearman"),3))
cat("top origins raw:\n"); print(head(sort(table(df$origin),decreasing=TRUE),8))
cat("blank origin/dest:",sum(df$origin==""|is.na(df$origin)),sum(df$destination==""|is.na(df$destination)),"\n")
cat("by month:\n"); print(table(substr(df$day,1,7)))
