suppressMessages({library(tidyverse);library(igraph)})
df <- read.csv("sampled_flights.csv")
cat("flights rows:",nrow(df),"\n")
cat("date range:",min(df$day),max(df$day),"\n")
s <- df |> select(origin,destination,latitude_1,longitude_1,latitude_2,longitude_2) |> drop_na()
cat("rows after drop_na:",nrow(s),"\n")
edges <- s |> group_by(origin,destination) |> summarise(weight=n(),.groups="drop")
o <- s |> select(name=origin,lat=latitude_1,long=longitude_1); d <- s |> select(name=destination,lat=latitude_2,long=longitude_2)
nodes <- bind_rows(o,d) |> distinct(name,.keep_all=TRUE) |> na.omit()
g <- graph_from_data_frame(edges,vertices=nodes,directed=TRUE)
g <- simplify(g,remove.multiple=TRUE,remove.loops=TRUE)
u <- as.undirected(g,mode="collapse")
wc <- components(g,mode="weak")
print(data.frame(V=vcount(g),E=ecount(g),simple=is_simple(g),weak=is_connected(g,"weak"),strong=is_connected(g,"strong"),ncomp=wc$no,lcc=max(wc$csize),diam=diameter(g,weights=NA),apl=round(mean_distance(g),4),dens=round(edge_density(g),6)))
d <- degree(u)
b <- cut(d, c(-1,0,1,2,5,10,20,100), labels=c("0","1","2","3-5","6-10","11-20","21+"))
print(table(b)); print(length(d))
print(sort(table(wc$csize),decreasing=TRUE)[1:6])
