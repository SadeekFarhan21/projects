suppressMessages({library(tidyverse);library(igraph)})
df <- read.csv("sampled_flights.csv")
s <- df |> select(origin,destination,latitude_1,longitude_1,latitude_2,longitude_2) |> drop_na()
edges <- s |> group_by(origin,destination) |> summarise(weight=n(),.groups="drop")
o <- s |> select(name=origin,lat=latitude_1,long=longitude_1); d <- s |> select(name=destination,lat=latitude_2,long=longitude_2)
nodes <- bind_rows(o,d) |> distinct(name,.keep_all=TRUE) |> na.omit()
g <- graph_from_data_frame(edges,vertices=nodes,directed=TRUE)
g <- simplify(g,remove.multiple=TRUE,remove.loops=TRUE)
u <- suppressWarnings(as.undirected(g,mode="collapse"))
cat("has weight attr (g,u):", "weight" %in% edge_attr_names(g), "weight" %in% edge_attr_names(u), "\n")
cat("weight summary u:\n"); print(summary(E(u)$weight))
top <- function(x,n=10) round(head(sort(x,decreasing=TRUE),n),4)
cat("betweenness weighted (default):\n"); print(top(betweenness(u,normalized=TRUE)))
cat("betweenness unweighted:\n"); print(top(betweenness(u,normalized=TRUE,weights=NA)))
cat("zero betweenness (weighted / unweighted):", sum(betweenness(u)==0), sum(betweenness(u,weights=NA)==0), "of", vcount(u), " nonzero:", sum(betweenness(u)>0), sum(betweenness(u,weights=NA)>0), "\n")
comp <- components(u); lcc <- induced_subgraph(u,which(comp$membership==which.max(comp$csize)))
cw <- closeness(lcc); cu <- closeness(lcc,weights=NA)
rk <- function(x,a) rank(-x,ties.method="min")[a]
for (a in c("KTPA","KCLT","KIAD","KDFW")) cat(a,"degree",degree(u)[a],"closeness rank weighted",rk(cw,a),"unweighted",rk(cu,a),"of",length(cw),"\n")
cat("closeness unweighted top10:\n"); print(names(sort(cu,decreasing=TRUE))[1:10])
cd <- data.frame(deg=degree(u),bet=betweenness(u),eig=eigen_centrality(u)$vector,str=strength(u))
cdu <- data.frame(deg=degree(u),bet=betweenness(u,weights=NA),eig=eigen_centrality(u,weights=NA)$vector,str=strength(u))
cat("Spearman weighted:\n"); print(round(cor(cd,method="spearman"),3))
cat("Spearman unweighted bet/eig:\n"); print(round(cor(cdu,method="spearman"),3))
cat("eigen top5 weighted:\n"); print(top(eigen_centrality(u)$vector,5)); cat("unweighted:\n"); print(top(eigen_centrality(u,weights=NA)$vector,5))
cat("NA origin:",sum(is.na(df$origin)),"empty-string origin:",sum(df$origin=="",na.rm=TRUE),"NA dest:",sum(is.na(df$destination)),"empty dest:",sum(df$destination=="",na.rm=TRUE),"\n")
